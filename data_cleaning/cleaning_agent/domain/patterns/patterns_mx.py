chain_re = re.compile(
    "|".join(f"(?:{p})" for p in CHAIN_REGEX),
    flags=re.IGNORECASE,
)

# Pasada agresiva: cadenas + patrones ambiguos. Úsala solo para revisión
# manual o cuando el costo de un falso negativo sea mayor que el de un
# falso positivo.
CHAIN_REGEX_FULL = CHAIN_REGEX + CHAIN_REGEX_AMBIGUOS

chain_re_full = re.compile(
    "|".join(f"(?:{p})" for p in CHAIN_REGEX_FULL),
    flags=re.IGNORECASE,
)


def es_cadena(nombre: str, agresivo: bool = False) -> bool:
    """True si el nombre corresponde a una cadena comercial (no target)."""
    if not nombre:
        return False
    return bool((chain_re_full if agresivo else chain_re).search(nombre))


def cadena_detectada(nombre: str, agresivo: bool = False):
    """Devuelve el texto que disparó el match, útil para auditar exclusiones."""
    if not nombre:
        return None
    m = (chain_re_full if agresivo else chain_re).search(nombre)
    return m.group(0) if m else None
