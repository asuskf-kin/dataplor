#   SMART   -> S-Mart (supermercado norte) vs Smart & Final (club noroeste)
#   MEGA    -> Mega Comercial Mexicana (pre-2016) vs Mega Soriana (post-2017)
#   BODEGA  -> Aurrerá / Comercial Mexicana / Gigante / Alianza / Su Bodega
